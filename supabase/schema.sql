-- Run once in Supabase SQL Editor. No public database access is enabled.
create table if not exists public.avci_images (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 60),
  creator text not null default 'community',
  image text not null check (char_length(image) <= 2048),
  description text not null default '' check (char_length(description) <= 500),
  created_at timestamptz not null default now()
);
alter table public.avci_images enable row level security;
grant select, insert on public.avci_images to service_role;

create table if not exists public.avci_post_limits (
  key_hash text primary key,
  window_started_at timestamptz not null,
  attempts integer not null
);
alter table public.avci_post_limits enable row level security;

-- This single atomic operation shares the limit across serverless instances.
create or replace function public.avci_add_image(p_key text, p_title text, p_image text, p_description text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  attempts_now integer;
  new_row public.avci_images;
begin
  insert into public.avci_post_limits as limits (key_hash, window_started_at, attempts)
  values (p_key, now(), 1)
  on conflict (key_hash) do update
    set attempts = case when limits.window_started_at <= now() - interval '1 hour' then 1 else limits.attempts + 1 end,
        window_started_at = case when limits.window_started_at <= now() - interval '1 hour' then now() else limits.window_started_at end
  returning attempts into attempts_now;
  if attempts_now > 5 then return jsonb_build_object('limited', true); end if;
  insert into public.avci_images(title, image, description)
  values (p_title, p_image, p_description)
  returning * into new_row;
  return jsonb_build_object('image', jsonb_build_object(
    'id', new_row.id, 'title', new_row.title, 'creator', new_row.creator,
    'image', new_row.image, 'description', new_row.description
  ));
end;
$$;
revoke all on function public.avci_add_image(text, text, text, text) from public, anon, authenticated;
grant execute on function public.avci_add_image(text, text, text, text) to service_role;
